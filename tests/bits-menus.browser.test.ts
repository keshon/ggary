import { afterEach, expect, it } from 'vitest'
import { mount, unmount, flushSync } from 'svelte'
import { userEvent } from '@vitest/browser/context'
import Pilot from './fixtures/BitsMenusPilot.svelte'
import '../packages/structure/src/index.css'
import '@ggary/theme-ggarry'
let instance: ReturnType<typeof mount> | undefined
const settle = async () => { await new Promise(resolve => setTimeout(resolve, 70)); flushSync() }
afterEach(async () => { if (instance) await unmount(instance); instance = undefined; document.body.replaceChildren() })
function setup() { const host = document.createElement('div'); document.body.append(host); instance = mount(Pilot, { target: host }); flushSync(); return host }
const button = (host: ParentNode, text: string) => [...host.querySelectorAll<HTMLButtonElement>('button')].find(el => el.textContent === text)!
const item = (text: string) => [...document.querySelectorAll<HTMLElement>('[role^="menuitem"]')].find(el => el.querySelector('[data-part="item-text"]')?.textContent === text)!
const menus = () => document.querySelectorAll('[role="menu"]')
it('opens lazily, reports owner-held checkbox state, selects a link, and returns focus', async () => {
  const host = setup(); const trigger = button(host, 'Actions')
  expect(menus()).toHaveLength(0)
  await userEvent.click(trigger); await settle()
  expect(menus()).toHaveLength(1)
  await userEvent.click(item('Show grid')); await settle()
  expect(item('Show grid').getAttribute('aria-checked')).toBe('true')
  expect(host.querySelector('output')!.textContent).toBe('grid')
  expect(menus()).toHaveLength(1)
  expect(item('Docs').tagName).toBe('A')
  await userEvent.click(item('Edit')); await settle()
  expect(host.querySelector('output')!.textContent).toBe('edit')
  expect(menus()).toHaveLength(0)
  expect(document.activeElement).toBe(trigger)
})
it('navigates two submenu levels, dismisses one layer per Escape, then selects exactly once', async () => {
  const host = setup(); const trigger = button(host, 'Actions')
  trigger.focus(); await userEvent.keyboard('{ArrowDown}'); await settle()
  expect(document.activeElement).toBe(item('Edit'))
  await userEvent.keyboard('{ArrowDown}'); await settle()
  expect(document.activeElement).toBe(item('Show grid'))
  await userEvent.keyboard('{ArrowDown}{ArrowRight}'); await settle()
  expect(document.activeElement).toBe(item('Alpha'))
  await userEvent.keyboard('{End}{ArrowRight}'); await settle()
  expect(document.activeElement).toBe(item('Beta'))
  expect(menus()).toHaveLength(3)
  await userEvent.keyboard('{Escape}'); await settle()
  expect(menus()).toHaveLength(2)
  expect(document.activeElement).toBe(item('More'))
  await userEvent.keyboard('{Escape}'); await settle()
  expect(menus()).toHaveLength(1)
  expect(document.activeElement).toBe(item('Recent'))
  await userEvent.keyboard('{ArrowRight}{Enter}'); await settle()
  expect(host.querySelector('output')!.textContent).toBe('alpha')
  expect(menus()).toHaveLength(0)
  expect(document.activeElement).toBe(trigger)
})
it('opens ContextMenu by pointer and keyboard, anchors to its target, and restores focus', async () => {
  const host = setup(); const target = host.querySelector<HTMLElement>('[data-context-menu-trigger]')!
  await userEvent.click(target, { button: 'right' }); await settle()
  expect(menus()).toHaveLength(1)
  expect(menus()[0].getBoundingClientRect().width).toBeGreaterThan(0)
  await userEvent.keyboard('{Escape}'); await settle()
  target.focus(); await userEvent.keyboard('{Shift>}{F10}{/Shift}'); await settle()
  expect(menus()).toHaveLength(1)
  await userEvent.click(item('Edit')); await settle()
  expect(host.querySelector('output')!.textContent).toBe('edit')
  expect(document.activeElement).toBe(target)
})
it('switches Menubar menus by arrows and supports access keys with originating-menu callbacks', async () => {
  const host = setup(); const file = button(host, 'File')
  file.focus(); await userEvent.keyboard('{ArrowDown}'); await settle()
  expect(document.activeElement).toBe(item('Edit'))
  await userEvent.keyboard('{ArrowRight}'); await settle()
  expect(document.activeElement).toBe(item('Zoom'))
  await userEvent.keyboard('{Enter}'); await settle()
  expect(host.querySelector('[aria-label="Selected menu"]')!.textContent).toBe('view')
  await userEvent.keyboard('{Alt>}f{/Alt}'); await settle()
  expect(menus()).toHaveLength(1)
  await userEvent.keyboard('{Escape}'); await settle()
  button(host, 'View').focus(); await userEvent.keyboard('{ArrowDown}'); await settle()
  await userEvent.keyboard('{F10}'); await settle()
  expect(menus()).toHaveLength(0)
  expect(document.activeElement).toBe(file)
})
it('routes submenu, menu and Dialog Escape independently and closes on outside interaction', async () => {
  const host = setup(); const opener = button(host, 'Open menu dialog')
  await userEvent.click(opener); await settle()
  const nested = button(document, 'Nested actions')
  nested.focus(); await userEvent.keyboard('{ArrowDown}'); await settle()
  await userEvent.keyboard('{ArrowDown}{ArrowDown}{ArrowRight}'); await settle()
  await userEvent.keyboard('{Escape}'); await settle()
  expect(menus()).toHaveLength(1)
  await userEvent.keyboard('{Escape}'); await settle()
  expect(menus()).toHaveLength(0)
  expect(document.activeElement).toBe(nested)
  expect(document.querySelector('[role="dialog"]')!.getAttribute('data-state')).toBe('open')
  await userEvent.keyboard('{Escape}'); await settle()
  expect(document.activeElement).toBe(opener)
  await userEvent.click(button(host, 'Actions')); await settle()
  await userEvent.click(host.querySelector('[data-context-menu-trigger]')!); await settle()
  expect(menus()).toHaveLength(0)
})

it('opens Menu and Menubar on the last row with ArrowUp and closes Menu on Tab', async () => {
  const host = setup(); const trigger = button(host, 'Actions')
  trigger.focus(); await userEvent.keyboard('{ArrowUp}'); await settle()
  expect(document.activeElement).toBe(item('Other radio'))
  await userEvent.keyboard('{Tab}'); await settle()
  expect(menus()).toHaveLength(0)
  expect(document.activeElement).toBe(trigger)
  button(host, 'File').focus(); await userEvent.keyboard('{ArrowUp}'); await settle()
  expect(document.activeElement).toBe(item('Other radio'))
  await userEvent.keyboard('{Escape}'); await settle()
  await userEvent.keyboard('{ArrowUp}'); await settle()
  expect(document.activeElement).toBe(item('Other radio'))
})

it('keeps empty-string radio and Menubar keys distinct from unselected state', async () => {
  const host = setup()
  expect(menus()).toHaveLength(0)
  await userEvent.click(button(host, 'Actions')); await settle()
  expect(item('Empty radio').getAttribute('aria-checked')).toBe('false')
  await userEvent.click(item('Empty radio')); await settle()
  // The owner refuses the request, so the visual selection does not change.
  expect(item('Empty radio').getAttribute('aria-checked')).toBe('false')
  expect(host.querySelector('output')!.textContent).toBe('')
  await userEvent.keyboard('{Escape}'); await settle()
  await userEvent.click(button(host, 'Empty')); await settle()
  expect(item('Empty action')).toBeTruthy()
  await userEvent.keyboard('{Escape}'); await settle()
  expect(menus()).toHaveLength(0)
})
